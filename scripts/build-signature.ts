/**
 * Generates src/lib/signature-path.ts: the "naandalist" signature as one SVG path, drawn from
 * Damion (SIL OFL, google/fonts ofl/damion), a casual slanted script like the Dribbble wordmark.
 * Run once when the text or font changes: bun run scripts/build-signature.ts <Damion-Regular.ttf>
 * opentype.js is a dev dependency only. The app ships the finished path, not a font parser.
 */
import opentype from 'opentype.js'

const fontFile = process.argv[2]
if (!fontFile) {
  console.error('usage: bun run scripts/build-signature.ts <Damion-Regular.ttf>')
  process.exit(1)
}

const TEXT = 'naandalist'
const SIZE = 64
const PAD = 2

const font = opentype.parse((await Bun.file(fontFile).arrayBuffer()) as ArrayBuffer)
const scale = SIZE / font.unitsPerEm

// Lay glyphs out by hand. opentype.js shaping (GSUB) fails on this font, and this word needs no ligatures.
const glyphs = [...TEXT].map((ch) => font.charToGlyph(ch))
let x = 0
const placed = glyphs.map((g, i) => {
  const path = g.getPath(x, 0, SIZE)
  const next = glyphs[i + 1]
  // Kerning can come back as NaN for pairs the font does not define, so only trust finite values.
  const kern = next ? font.getKerningValue(g, next) : 0
  x += (g.advanceWidth ?? font.unitsPerEm) * scale + (Number.isFinite(kern) ? kern * scale : 0)
  return path
})

const merged = new opentype.Path()
for (const p of placed) merged.extend(p)
const box = merged.getBoundingBox()
const dx = PAD - box.x1
const dy = PAD - box.y1
const shifted = new opentype.Path()
for (const cmd of merged.commands) {
  const c = { ...cmd } as Record<string, number | string>
  for (const k of ['x', 'x1', 'x2']) if (typeof c[k] === 'number') c[k] = (c[k] as number) + dx
  for (const k of ['y', 'y1', 'y2']) if (typeof c[k] === 'number') c[k] = (c[k] as number) + dy
  shifted.commands.push(c as never)
}
// Serialize by hand. toPathData() optimizes quadratics and can emit NaN for this font.
const r = (n: number) => Number(n.toFixed(1))
const d = (shifted.commands as unknown as Record<string, number | string>[])
  .map((c) => {
    switch (c.type) {
      case 'M':
      case 'L':
        return `${c.type}${r(c.x as number)} ${r(c.y as number)}`
      case 'Q':
        return `Q${r(c.x1 as number)} ${r(c.y1 as number)} ${r(c.x as number)} ${r(c.y as number)}`
      case 'C':
        return `C${r(c.x1 as number)} ${r(c.y1 as number)} ${r(c.x2 as number)} ${r(c.y2 as number)} ${r(c.x as number)} ${r(c.y as number)}`
      default:
        return 'Z'
    }
  })
  .join('')
const width = Math.ceil(box.x2 - box.x1 + PAD * 2)
const height = Math.ceil(box.y2 - box.y1 + PAD * 2)

const out = `// Generated by scripts/build-signature.ts from Damion. Do not edit by hand.
export const SIGNATURE = {
  d: '${d}',
  width: ${width},
  height: ${height},
} as const
`
if (/NaN|Infinity/.test(out)) throw new Error('signature path contains NaN or Infinity')
await Bun.write('src/lib/signature-path.ts', out)
console.log(`signature ${width}x${height}, ${d.length} chars`)
